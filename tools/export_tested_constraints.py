"""Export the installed dependency closure; use only in the tested target environment.

This is an exact-version environment snapshot, not a hash-locked universal wheel
resolver. Linux CI uses requirements-dev.txt and a CPU-specific PyTorch wheel.
"""
from importlib import metadata
from pathlib import Path
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name


def main():
    roots = ['numpy', 'pandas', 'openpyxl', 'pyarrow', 'torch', 'transformers',
             'sentence-transformers', 'scikit-learn', 'pytest', 'ruff', 'PyYAML']
    queue = [(name, frozenset()) for name in roots]
    seen, versions = set(), {}
    while queue:
        name, extras = queue.pop()
        name = canonicalize_name(name)
        if (name, extras) in seen:
            continue
        seen.add((name, extras))
        distribution = metadata.distribution(name)
        versions[name] = distribution.version
        for text in distribution.requires or ():
            requirement = Requirement(text)
            if requirement.marker is None or any(requirement.marker.evaluate({'extra': extra}) for extra in ('', *extras)):
                queue.append((requirement.name, frozenset(requirement.extras)))
    target = Path('constraints-macos-arm64.txt')
    target.write_text('# Tested CPython 3.12, macOS arm64 runtime/test dependency closure.\n'
                      '# Generated by tools/export_tested_constraints.py; platform-specific, no wheel hashes.\n'
                      + ''.join(f'{name}=={version}\n' for name, version in sorted(versions.items())))
    print(f'Wrote {len(versions)} exact installed versions to {target}')


if __name__ == '__main__':
    main()
